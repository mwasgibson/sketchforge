/**
 * Role-specific exports from Design Tree / canvas shapes.
 */

import type { DesignTree, DesignNode, Role } from '../types/designTree'
import type { Shape } from '../store/useCanvasStore'
import { shapesToDesignTree, flattenNodes } from './shapeBridge'

export type CodeTarget = 'react-tailwind' | 'html-css' | 'vue' | 'svelte' | 'structured'

export const CODE_TARGETS: { id: CodeTarget; label: string }[] = [
  { id: 'react-tailwind', label: 'React + Tailwind' },
  { id: 'html-css', label: 'HTML + CSS' },
  { id: 'vue', label: 'Vue 3' },
  { id: 'svelte', label: 'Svelte' },
  { id: 'structured', label: 'Structured JSON' },
]

function ensureTree(shapes: Shape[], role: Role, title: string, existing?: DesignTree | null): DesignTree {
  if (existing) return existing
  return shapesToDesignTree(shapes, role, title)
}

function walkNodes(node: DesignNode, fn: (n: DesignNode) => void) {
  fn(node)
  node.children?.forEach((c) => walkNodes(c, fn))
}

function styleToInline(n: DesignNode): string {
  const s = n.style || {}
  const parts: string[] = []
  if (s.fill && s.fill !== 'transparent') parts.push(`background:${s.fill}`)
  if (s.stroke) parts.push(`border:${s.strokeWidth ?? 1}px solid ${s.stroke}`)
  if (s.cornerRadius) parts.push(`border-radius:${s.cornerRadius}px`)
  if (s.fontSize) parts.push(`font-size:${s.fontSize}px`)
  if (s.fontFamily) parts.push(`font-family:${s.fontFamily}`)
  if (s.opacity != null && s.opacity < 1) parts.push(`opacity:${s.opacity}`)
  if (n.width) parts.push(`width:${n.width}px`)
  if (n.height) parts.push(`height:${n.height}px`)
  return parts.join(';')
}

function styleToTw(n: DesignNode): string {
  const s = n.style || {}
  const cls: string[] = ['relative']
  if (s.cornerRadius && s.cornerRadius >= 8) cls.push('rounded-lg')
  else if (s.cornerRadius) cls.push('rounded')
  if (s.fontSize && s.fontSize >= 24) cls.push('text-2xl font-semibold')
  else if (s.fontSize && s.fontSize >= 16) cls.push('text-base')
  else cls.push('text-sm')
  if (n.type === 'component' && (n as { componentType?: string }).componentType === 'Button') {
    cls.push('inline-flex items-center justify-center px-4 py-2 bg-blue-500 text-white rounded-lg')
  }
  return cls.join(' ')
}

function nodeLabel(n: DesignNode): string {
  if (n.type === 'text') return (n as { text?: string }).text || 'Text'
  if (n.type === 'component') return (n as { componentType?: string }).componentType || n.name || 'Component'
  return n.name || n.type
}

/** ---------- Developer: code generation ---------- */

export function generateCode(
  tree: DesignTree,
  target: CodeTarget
): { filename: string; content: string } {
  const flat = flattenNodes(tree.root).map((x) => x.node)

  if (target === 'structured') {
    return {
      filename: 'design.json',
      content: JSON.stringify(tree, null, 2),
    }
  }

  if (target === 'react-tailwind') {
    const lines: string[] = [
      `/** Generated by SketchForge — ${tree.meta.title} */`,
      `export default function Mockup() {`,
      `  return (`,
      `    <div className="relative min-h-screen bg-neutral-950 text-neutral-100 p-6">`,
    ]
    for (const n of flat) {
      if (n.type === 'frame' && n.id === tree.root.id) continue
      const tw = styleToTw(n)
      if (n.type === 'text') {
        lines.push(
          `      <p className="${tw}" style={{ left: ${n.x}, top: ${n.y} }}>` +
            `${escapeJsx((n as { text?: string }).text || '')}</p>`
        )
      } else if (n.type === 'component') {
        const ct = (n as { componentType?: string; text?: string }).componentType
        const tx = (n as { text?: string }).text || ct
        lines.push(
          `      <div className="${tw}" style={{ width: ${n.width}, height: ${n.height} }}>` +
            `${escapeJsx(tx || '')}</div>`
        )
      } else if (n.type === 'rect' || n.type === 'frame') {
        lines.push(
          `      <div className="${tw} border border-neutral-700" style={{ width: ${n.width}, height: ${n.height} }} />`
        )
      } else if (n.type === 'ellipse') {
        lines.push(
          `      <div className="${tw} rounded-full border border-neutral-700" style={{ width: ${n.width}, height: ${n.height} }} />`
        )
      }
    }
    lines.push(`    </div>`, `  )`, `}`, ``)
    return { filename: 'Mockup.tsx', content: lines.join('\n') }
  }

  if (target === 'html-css') {
    const css: string[] = [
      `/* SketchForge — ${tree.meta.title} */`,
      `* { box-sizing: border-box; }`,
      `body { margin: 0; font-family: Inter, system-ui, sans-serif; background: #0f0f0f; color: #f0f0f0; }`,
      `.artboard { position: relative; min-height: 100vh; padding: 24px; }`,
    ]
    const html: string[] = [
      `<!DOCTYPE html>`,
      `<html lang="en">`,
      `<head><meta charset="utf-8" /><title>${escapeHtml(tree.meta.title)}</title>`,
      `<link rel="stylesheet" href="styles.css" /></head>`,
      `<body><div class="artboard">`,
    ]
    let i = 0
    for (const n of flat) {
      if (n.type === 'frame' && n.id === tree.root.id) continue
      const id = `n${i++}`
      const inline = styleToInline(n)
      css.push(`.${id} { position: absolute; left: ${n.x}px; top: ${n.y}px; ${inline}; }`)
      if (n.type === 'text') {
        html.push(`  <p class="${id}">${escapeHtml((n as { text?: string }).text || '')}</p>`)
      } else {
        html.push(`  <div class="${id}"></div>`)
      }
    }
    html.push(`</div></body></html>`, ``)
    return {
      filename: 'index.html',
      content: html.join('\n') + '\n/* --- styles.css --- */\n' + css.join('\n'),
    }
  }

  if (target === 'vue') {
    const body: string[] = []
    for (const n of flat) {
      if (n.type === 'frame' && n.id === tree.root.id) continue
      if (n.type === 'text') {
        body.push(`    <p class="node">${escapeHtml((n as { text?: string }).text || '')}</p>`)
      } else {
        body.push(`    <div class="node box" />`)
      }
    }
    const content = [
      `<script setup lang="ts">`,
      `/** SketchForge — ${tree.meta.title} */`,
      `</script>`,
      `<template>`,
      `  <div class="artboard">`,
      ...body,
      `  </div>`,
      `</template>`,
      `<style scoped>`,
      `.artboard { min-height: 100vh; padding: 24px; background: #0f0f0f; color: #f0f0f0; }`,
      `.node { margin-bottom: 8px; }`,
      `.box { width: 120px; height: 40px; border: 1px solid #64748b; border-radius: 8px; }`,
      `</style>`,
      ``,
    ].join('\n')
    return { filename: 'Mockup.vue', content }
  }

  if (target === 'svelte') {
    const body: string[] = []
    for (const n of flat) {
      if (n.type === 'frame' && n.id === tree.root.id) continue
      if (n.type === 'text') {
        body.push(`  <p class="node">${escapeHtml((n as { text?: string }).text || '')}</p>`)
      } else {
        body.push(`  <div class="node box"></div>`)
      }
    }
    const content = [
      `<!-- SketchForge — ${tree.meta.title} -->`,
      `<div class="artboard">`,
      ...body,
      `</div>`,
      `<style>`,
      `.artboard { min-height: 100vh; padding: 24px; background: #0f0f0f; color: #f0f0f0; font-family: Inter, system-ui, sans-serif; }`,
      `.node { margin-bottom: 8px; }`,
      `.box { width: 120px; height: 40px; border: 1px solid #64748b; border-radius: 8px; }`,
      `</style>`,
      ``,
    ].join('\n')
    return { filename: 'Mockup.svelte', content }
  }

  return { filename: 'design.json', content: JSON.stringify(tree, null, 2) }
}

/** ---------- Designer: tokens ---------- */

export function generateTokens(tree: DesignTree): {
  json: string
  css: string
  filenameJson: string
  filenameCss: string
} {
  const colors = new Set<string>()
  const fonts = new Set<string>()
  const radii = new Set<number>()

  walkNodes(tree.root, (n) => {
    if (n.style?.fill && !n.style.fill.startsWith('rgba') && n.style.fill !== 'transparent') {
      colors.add(n.style.fill)
    }
    if (n.style?.stroke) colors.add(n.style.stroke)
    if (n.style?.fontFamily) fonts.add(n.style.fontFamily)
    if (n.style?.cornerRadius) radii.add(n.style.cornerRadius)
  })

  Object.values(tree.tokens?.colors || {}).forEach((c) => colors.add(c))
  Object.values(tree.tokens?.fonts || {}).forEach((f) => fonts.add(f))
  Object.values(tree.tokens?.radii || {}).forEach((r) => radii.add(r))

  const colorEntries = [...colors]
  const fontEntries = [...fonts]
  const radiusEntries = [...radii].sort((a, b) => a - b)

  const tokenObj = {
    color: Object.fromEntries(colorEntries.map((c, i) => [`color${i + 1}`, c])),
    font: Object.fromEntries(fontEntries.map((f, i) => [`font${i + 1}`, f])),
    radius: Object.fromEntries(radiusEntries.map((r, i) => [`r${i + 1}`, r])),
    meta: { source: tree.meta.title, role: tree.role },
  }

  const cssLines = [
    `/* SketchForge tokens — ${tree.meta.title} */`,
    `:root {`,
    ...colorEntries.map((c, i) => `  --color-${i + 1}: ${c};`),
    ...fontEntries.map((f, i) => `  --font-${i + 1}: ${f};`),
    ...radiusEntries.map((r, i) => `  --radius-${i + 1}: ${r}px;`),
    `}`,
    ``,
  ]

  return {
    json: JSON.stringify(tokenObj, null, 2),
    css: cssLines.join('\n'),
    filenameJson: 'tokens.json',
    filenameCss: 'tokens.css',
  }
}

/** ---------- Marketer: brief ---------- */

export function generateBrief(tree: DesignTree, shapes: Shape[]): string {
  const nodes = flattenNodes(tree.root).map((x) => x.node)
  const texts = nodes
    .filter((n) => n.type === 'text' || (n.type === 'component' && (n as { text?: string }).text))
    .map((n) => (n as { text?: string }).text || nodeLabel(n))

  const frames = nodes.filter((n) => n.type === 'frame')
  const lines = [
    `# Campaign brief — ${tree.meta.title}`,
    ``,
    `**Role context:** ${tree.role}`,
    `**Generated:** ${new Date().toISOString().slice(0, 10)}`,
    ``,
    `## Intent`,
    tree.meta.intent || 'Visual mockup derived from sketch.',
    ``,
    `## Frames / sizes`,
    frames.length
      ? frames.map((f) => `- ${f.name || f.type}: ${f.width}×${f.height}`).join('\n')
      : `- Artboard from ${shapes.length} layers`,
    ``,
    `## Copy / labels detected`,
    texts.length ? texts.map((t) => `- ${t}`).join('\n') : '- (no text layers yet)',
    ``,
    `## Suggested next steps`,
    `1. Export PNG assets at required ad sizes.`,
    `2. Refine headline and CTA copy.`,
    `3. Hand agent payload to creative or media agent for variants.`,
    ``,
  ]
  return lines.join('\n')
}

/** Download helpers */
export function downloadText(filename: string, content: string, mime = 'text/plain') {
  const blob = new Blob([content], { type: mime })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  URL.revokeObjectURL(url)
}

export function downloadDataUrl(filename: string, dataUrl: string) {
  const a = document.createElement('a')
  a.href = dataUrl
  a.download = filename
  a.click()
}

function escapeHtml(s: string) {
  return s.replace(/&/g, '&').replace(/</g, '<').replace(/>/g, '>').replace(/"/g, '"')
}

function escapeJsx(s: string) {
  return s.replace(/\{/g, '&#123;').replace(/\}/g, '&#125;').replace(/</g, '<')
}

